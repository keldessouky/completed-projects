def parse():
    """Returns a 138-entry list of 7-byte glyph rows, indexed by character code."""
    glyphs = [[0] * 7 for _ in range(138)]
    for block in (GLYPHS, EXTRA):
        for line in block.strip().splitlines():
            parts = line.split()
            if not parts:
                continue
            name, rows = parts[0], parts[1:8]
            if name == "SPACE":
                code = 32
            elif name.isdigit() and len(name) > 1:
                code = int(name)
            else:
                code = ord(name)
            if len(rows) != 7:
                raise ValueError("glyph %r has %d rows" % (name, len(rows)))
            for y, row in enumerate(rows):
                if len(row) != 5:
                    raise ValueError("glyph %r row %d is %d wide" % (name, y, len(row)))
                bits = 0
                for x, ch in enumerate(row):
                    if ch == '#':
                        bits |= 1 << (4 - x)
                glyphs[code][y] = bits
    return glyphs



import { CONFIG } from '../config';

/**
 * Liberated Pixel Cup character layers.
 *
 * LPC sheets are a fixed grid: 64×64 frames, one row per facing in the order
 * up, left, down, right, and one column per animation frame. Every layer — body,
 * legs, torso, head, helmet, weapon — shares that grid exactly, so a character
 * is built by stacking layers in z order and reading the same cell from each.
 *
 * That is why this is worth the trouble over drawing characters procedurally:
 * the walk is nine hand-drawn frames per facing with real weight in it, and the
 * gear is drawn to match the body pose frame for frame. Nothing generated at
 * this size competes with it.
 *
 * Attribution for every file lives in `public/lpc/CREDITS.md`, regenerated by
 * `tools/vendor-lpc.mjs`. OGA-BY and CC-BY-SA both require it to ship.
 */

/** side of one LPC cell, in pixels */
export const CELL = 64;

/** Row order inside every LPC sheet. */
export const DIR = { up: 0, left: 1, down: 2, right: 3 } as const;
export type DirName = keyof typeof DIR;

/**
 * Facings actually baked. `left` is omitted and drawn by flipping `right`:
 * LPC draws it as its own art, but at this size the only difference is which
 * hand the weapon is in, and halving the unit frames is what keeps the sheet
 * inside one texture.
 */
export const BAKED_DIRS: DirName[] = ['up', 'down', 'right'];

/** Frames per animation in the sheets we ship. */
export const LPC_WALK = 9;
export const LPC_THRUST = 8;
export const LPC_SHOOT = 13;

/**
 * Attack frames baked per unit. The thrust and shoot cycles are longer than
 * this, but they spend most of their length on the wind-up; sampling evenly
 * across the cycle keeps the recognisable poses and a third of the atlas cost.
 */
export const ATTACK_BAKED = 6;

export type Anim = 'walk' | 'thrust' | 'shoot';

/** One stacked layer of a character. Higher `z` paints later. */
export interface Layer {
  /** vendored sheet name, without the `_<anim>.png` suffix */
  sheet: string;
  z: number;
  /**
   * Recolour applied to this layer only, as a multiply. Era progression rides
   * on this: the same plate armour becomes iron, brass, steel, olive drab and
   * neon without five sets of art.
   */
  tint?: number;
  /** skip this layer when the animation is missing from the vendored set */
  optional?: boolean;
}

const IMAGES = new Map<string, HTMLImageElement>();

function loadImage(url: string): Promise<HTMLImageElement | null> {
  return new Promise((resolve) => {
    const img = new Image();
    img.onload = () => resolve(img);
    img.onerror = () => resolve(null);
    img.src = url;
  });
}

/**
 * Load every vendored sheet named by `sheets`, for every animation. Missing
 * combinations resolve to null and are simply skipped when compositing, so a
 * layer that has no `shoot` art costs a hole in that pose rather than a crash.
 */
export async function loadLpc(base: string, sheets: string[], anims: Anim[]): Promise<void> {
  // the one-file build has nowhere to fetch from and inlines the sheets instead
  const embedded = (window as unknown as { __CC_LPC__?: Record<string, string> }).__CC_LPC__;
  const jobs: Promise<void>[] = [];
  for (const s of sheets) {
    for (const a of anims) {
      const key = `${s}_${a}`;
      const src = embedded?.[`${key}.png`] ?? `${base}lpc/${key}.png`;
      jobs.push(loadImage(src).then((img) => {
        if (img) IMAGES.set(key, img);
      }));
    }
  }
  await Promise.all(jobs);
}

export const hasSheet = (sheet: string, anim: Anim): boolean => IMAGES.has(`${sheet}_${anim}`);

/** Scratch canvases: one to tint a single layer, one to stack the result. */
let tintCv: HTMLCanvasElement | null = null;
let tintCtx: CanvasRenderingContext2D | null = null;

function tinted(img: HTMLImageElement, sx: number, sy: number, tint: number): CanvasImageSource {
  if (!tintCv) {
    tintCv = document.createElement('canvas');
    tintCv.width = CELL;
    tintCv.height = CELL;
    tintCtx = tintCv.getContext('2d')!;
  }
  const c = tintCtx!;
  c.globalCompositeOperation = 'source-over';
  c.clearRect(0, 0, CELL, CELL);
  c.drawImage(img, sx, sy, CELL, CELL, 0, 0, CELL, CELL);
  // multiply keeps the art's own shading and pushes it toward the era colour;
  // source-atop then confines the result to the pixels the layer already drew,
  // so the transparent margin stays transparent
  c.globalCompositeOperation = 'multiply';
  c.fillStyle = '#' + (tint >>> 0).toString(16).padStart(6, '0');
  c.fillRect(0, 0, CELL, CELL);
  c.globalCompositeOperation = 'destination-in';
  c.drawImage(img, sx, sy, CELL, CELL, 0, 0, CELL, CELL);
  c.globalCompositeOperation = 'source-over';
  return tintCv;
}

/**
 * Draw one composited character cell into `dst` at (dx, dy).
 *
 * `frame` indexes the animation's own frame count, `dir` picks the row. Layers
 * are painted in ascending z; a layer with no art for this animation is
 * skipped, which is how a weapon that only has a walk sheet still works.
 */
export function drawCell(
  dst: CanvasRenderingContext2D,
  layers: Layer[],
  anim: Anim,
  dir: DirName,
  frame: number,
  dx: number,
  dy: number,
): void {
  const row = DIR[dir];
  for (const l of [...layers].sort((a, b) => a.z - b.z)) {
    const img = IMAGES.get(`${l.sheet}_${anim}`);
    if (!img) continue;
    const cols = Math.max(1, Math.floor(img.naturalWidth / CELL));
    const sx = (frame % cols) * CELL;
    const sy = row * CELL;
    if (sy + CELL > img.naturalHeight) continue;
    if (l.tint !== undefined) dst.drawImage(tinted(img, sx, sy, l.tint), dx, dy);
    else dst.drawImage(img, sx, sy, CELL, CELL, dx, dy, CELL, CELL);
  }
}

/** How many frames an animation's sheets actually have. */
export function frameCount(anim: Anim): number {
  return anim === 'walk' ? LPC_WALK : anim === 'thrust' ? LPC_THRUST : LPC_SHOOT;
}

/**
 * Evenly sample `ATTACK_BAKED` frames out of an attack cycle, always including
 * the first and last so the pose starts at rest and ends at full extension.
 */
export function attackFrameAt(anim: Anim, i: number): number {
  const n = frameCount(anim);
  return Math.round((i / (ATTACK_BAKED - 1)) * (n - 1));
}


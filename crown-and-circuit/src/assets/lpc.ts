/**
 * The layer stack for a soldier or king, per era and tier.
 *
 * Tier picks the armour — leather levy, chainmail drilled, plate elite — and
 * the era recolours it, so fifteen distinct-looking soldiers come out of three
 * sets of art. z values follow LPC's own ordering: body under legs under torso
 * under head under helmet, with the weapon on top.
 */
export function unitLayers(era: number, tier: number, royal: boolean): Layer[] {
  const pal = CONFIG.palettes[era];
  const metal = ERA_METAL[era];
  // The king wears the same plate as an elite, pushed gold. LPC's armour is cut
  // for the standard body, not the muscular one — putting it on the muscular
  // base leaves the chest bare, so the king is distinguished by colour and
  // crest rather than by frame size.
  const royalGold = 0xe6c46a;
  const torso = royal ? 'torso_plate' : tier === 0 ? 'torso_leather' : tier === 1 ? 'torso_chain' : 'torso_plate';
  const legs = royal || tier === 2 ? 'legs_plate' : 'legs_pants';
  const feet = royal || tier === 2 ? 'feet_plate' : 'feet_boots';
  const helm = royal
    ? 'helm_armet'
    : tier === 0 ? 'hat_cloth' : tier === 1 ? 'helm_legion' : era >= 3 ? 'helm_xeon' : 'helm_bascinet';

  const armour = royal ? royalGold : metal;
  const layers: Layer[] = [
    { sheet: 'body_male', z: 10 },
    // cloth takes the era's accent, plate takes its metal — tinting trousers
    // with steel makes them look like foil
    { sheet: legs, z: 25, tint: legs === 'legs_plate' ? armour : undefined },
    { sheet: feet, z: 30, tint: feet === 'feet_plate' ? armour : undefined },
    { sheet: torso, z: 60, tint: torso === 'torso_leather' ? undefined : armour },
    { sheet: 'head_human', z: 100 },
    { sheet: helm, z: 130, tint: helm === 'hat_cloth' ? undefined : armour },
  ];
  // LPC covers the ends of the arc: a longsword for the iron age and a glowing
  // blade for neon. The powder, industry and steel eras have no firearms in the
  // set at all, so their weapons are drawn by the game — see weaponOverlay().
  if (era === 0) layers.push({ sheet: 'weapon_sword', z: 140 });
  else if (era === 4) layers.push({ sheet: 'weapon_glow', z: 140, tint: pal.accent });
  return layers;
}

/**
 * Era metal colours. Multiplied over LPC's own grey steel, so the shading and
 * highlights are the original artists' and only the hue moves.
 */
const ERA_METAL = [0xb9c0c8, 0xc9a06a, 0x8fa2b4, 0x8d9478, 0x9fd8e8];

/** Monster layer stacks for the horde. */
export function enemyLayers(kind: string): Layer[] {
  switch (kind) {
    case 'runner':
      return [{ sheet: 'body_skeleton', z: 10 }, { sheet: 'head_skeleton', z: 100 }];
    case 'brute':
      return [
        { sheet: 'body_king', z: 10 }, { sheet: 'head_minotaur', z: 100 },
        { sheet: 'legs_pants', z: 25 }, { sheet: 'feet_boots', z: 30 },
      ];   // the muscular base, bare-chested: a brute should not look kitted out
    case 'shooter':
      return [{ sheet: 'body_zombie', z: 10 }, { sheet: 'head_zombie', z: 100 }];
    case 'boss':
      return [
        { sheet: 'body_male', z: 10 }, { sheet: 'head_orc', z: 100 },
        { sheet: 'torso_plate', z: 60 }, { sheet: 'legs_plate', z: 25 },
        { sheet: 'feet_plate', z: 30 }, { sheet: 'weapon_sword', z: 140 },
      ];
    default:
      return [{ sheet: 'body_skeleton', z: 10 }, { sheet: 'head_goblin', z: 100 }];
  }
}

